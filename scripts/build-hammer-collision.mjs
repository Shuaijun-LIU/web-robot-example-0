// Emit a model-derived convex decomposition. Redirecting output is optional;
// the generated module is checked in so browser builds need no mesh tooling.
import { readFileSync } from 'node:fs';
import { Vector3 } from 'three';
import { ConvexHull } from 'three/addons/math/ConvexHull.js';
const vertices = [], triangles = [];
for (const line of readFileSync('public/assets/franka-assembly2/tools/robotwin-hammer.obj', 'utf8').split('\n')) {
  if (line.startsWith('v ')) {
    const [x,y,z] = line.trim().split(/\s+/).slice(1).map(Number);
    vertices.push([x*.11, -z*.11, y*.11-.008]);
  }
  if (line.startsWith('f ')) {
    const ids=line.trim().split(/\s+/).slice(1).map(s=>Number(s.split('/')[0])-1);
    for(let i=1;i<ids.length-1;i++) triangles.push([vertices[ids[0]],vertices[ids[i]],vertices[ids[i+1]]]);
  }
}
function clip(points, axis, boundary, sign) {
  const out=[];
  for(let i=0;i<points.length;i++) {
    const a=points[i], b=points[(i+1)%points.length];
    const da=(a[axis]-boundary)*sign, db=(b[axis]-boundary)*sign;
    if(da>=0) out.push(a);
    if((da>=0)!==(db>=0)) {const t=da/(da-db);out.push(a.map((v,j)=>v+(b[j]-v)*t));}
  }
  return out;
}
const pieces=[];
for(let i=0;i<15;i++) {
  const min=-.105+i*.01, max=min+.01;
  pieces.push({name:`handle_${i}`,bounds:[[0,min,max]]});
}
for(let i=0;i<11;i++) pieces.push({name:`head_${i}`,bounds:[[0,.045,.105],[1,-.077+i*.014,-.063+i*.014]]});
const meshes=pieces.flatMap(({name,bounds})=>{
  const pts=triangles.flatMap(tri=>bounds.reduce((p,[axis,min,max])=>clip(clip(p,axis,min,1),axis,max,-1),tri));
  const unique=[...new Map(pts.map(p=>[p.map(x=>x.toFixed(7)).join(' '),p])).values()];
  if(unique.length<4) return [];
  const extreme=new Set();
  for(const x of [-1,0,1]) for(let i=0;i<24;i++) {
    const y=Math.cos(i*Math.PI/12),z=Math.sin(i*Math.PI/12);
    extreme.add(unique.reduce((a,b)=>a[0]*x+a[1]*y+a[2]*z>b[0]*x+b[1]*y+b[2]*z?a:b));
  }
  const hull=new ConvexHull().setFromPoints([...extreme].map(p=>new Vector3(...p)));
  const used=[],faces=[];
  for(const face of hull.faces){let e=face.edge;const f=[];do{const p=e.head().point;let index=used.indexOf(p);if(index<0){index=used.length;used.push(p);}f.push(index);e=e.next;}while(e!==face.edge);faces.push(f);}
  return [{name,vertex:used.flatMap(p=>p.toArray().map(v=>Number(v.toFixed(7)))),face:faces.flat()}];
});
console.log('// Generated by scripts/build-hammer-collision.mjs from the visible RoboTwin OBJ.');
console.log('export const HAMMER_COLLISION_MESHES = '+JSON.stringify(meshes)+';');
console.log(`export const HAMMER_COLLISION_ASSETS = HAMMER_COLLISION_MESHES.map(p => '<mesh name="hammer_surface_' + p.name + '" vertex="' + p.vertex.join(' ') + '" face="' + p.face.join(' ') + '"/>').join('\\n');`);
console.log(`export const HAMMER_COLLISION_GEOMS = HAMMER_COLLISION_MESHES.map(p => '<geom name="robotwin_hammer_' + p.name + '_collision" type="mesh" mesh="hammer_surface_' + p.name + '" rgba="0 0 0 0" mass=".0015" friction="2 .05 .005" condim="6" priority="1" solref=".002 1" solimp=".99 .999 .0001"/>').join('\\n');`);
